import type { PublishedNoteSummary } from "../shared/api.ts";
import { PUBLISH_COMPONENT_SCHEMAS, PUBLISH_REQUEST_SCHEMA } from "../shared/publishing.ts";
import { INKS, PAPERS } from "../shared/appearance.ts";
import { STYLES, TEMPLATES } from "../shared/options.ts";
import { DOODLE_MODES } from "../shared/settings.ts";

const ids = (list: readonly { id: string }[]) => list.map((item) => item.id);

const summarySchema = {
  type: "object",
  properties: {
    id: { type: "string" },
    url: { type: "string", format: "uri", description: "给用户查看的链接" },
    title: { type: "string" },
    summary: { type: "string" },
    language: { type: "string", enum: ["zh", "en"] },
    template: { type: "string" },
    layout: { type: "string" },
    visibility: { type: "string", enum: ["public", "unlisted"] },
    createdAt: { type: "string", format: "date-time" },
    updatedAt: { type: "string", format: "date-time" },
  },
} as const;

const errorResponse = {
  description: "错误",
  content: {
    "application/json": {
      schema: {
        type: "object",
        properties: { error: { type: "object", required: ["code", "message"], properties: {
          code: { type: "string" }, message: { type: "string" }, requestId: { type: "string" },
          issues: { type: "array", items: { type: "object", required: ["path", "code", "message"],
            properties: { path: { type: "string" }, code: { type: "string" }, message: { type: "string" } } } },
        } } },
      },
    },
  },
} as const;

const noteIdParam = { name: "id", in: "path", required: true, schema: { type: "string", pattern: "^[A-Za-z0-9_-]{22}$" } } as const;

const validationSchema = {
  type: "object", required: ["structure", "layout"],
  properties: { structure: { const: "passed" }, layout: { const: "not_checked" } },
} as const;
const legacySettingsSchema = {
  ...PUBLISH_COMPONENT_SCHEMAS.Settings,
  properties: {
    ...PUBLISH_COMPONENT_SCHEMAS.Settings.properties,
    doodleMode: { type: "string", enum: DOODLE_MODES },
  },
} as const;
const publicationProperties = {
  note: { $ref: "#/components/schemas/NoteStructure" },
  stickers: { $ref: "#/components/schemas/Stickers" },
  meta: { type: "object", properties: {
    requestId: { type: "string" }, processing: { const: "agent" }, replayed: { type: "boolean" },
    validation: validationSchema,
  } },
} as const;
const publicationSchema = {
  allOf: [summarySchema, { oneOf: [
    {
      type: "object", required: ["schemaVersion", "note", "settings", "stickers"],
      properties: {
        ...publicationProperties,
        schemaVersion: { type: "integer", const: 1 },
        settings: { $ref: "#/components/schemas/Settings" },
      },
    },
    {
      type: "object", required: ["schemaVersion", "note", "settings", "stickers"],
      description: "Normalized content: notes published before the strict contract keep their legacy illustration settings, and stored snapshots that no longer pass it are served this way.",
      properties: {
        ...publicationProperties,
        schemaVersion: { type: "integer", const: 0 },
        settings: { $ref: "#/components/schemas/LegacySettings" },
        doodle: { $ref: "#/components/schemas/DoodleSpec" },
      },
    },
  ] }],
} as const;
const publishBody = {
  required: true,
  content: { "application/json": { schema: { $ref: "#/components/schemas/PublishRequest" } } },
} as const;
const publishedResponse = {
  description: "Published document and share URL; geometry is checked in the browser, no image is generated by the API.",
  content: { "application/json": { schema: publicationSchema } },
} as const;
// Publishing without a key accepts only unlisted notes; the shared validator keeps public for key holders.
const keylessPublishRequest = {
  ...PUBLISH_REQUEST_SCHEMA,
  properties: {
    ...PUBLISH_REQUEST_SCHEMA.properties,
    visibility: { type: "string", enum: ["unlisted"], default: "unlisted" },
  },
};
const createdResponse = {
  ...publishedResponse,
  content: { "application/json": { schema: { allOf: [publicationSchema, {
    type: "object", required: ["manageToken"],
    properties: { manageToken: { type: "string", description: "Credential for deleting this note (X-Manage-Token): the one the request supplied, or one generated by the server. Only its hash is stored, and replays do not return it; give it to the user." } },
  }] } } },
} as const;

export function openApiSpec() {
  return {
    openapi: "3.1.0",
    info: {
      title: "墨语笔记 InkScribe API",
      version: "1.1.0",
      description:
        "Publish agent-prepared note data without an account, a key, source text, or an AI call. schemaVersion: 1 and note are required. Notes are unlisted; requests are rate-limited per client IP with a 24-hour publishing limit. The manageToken (supplied in X-Manage-Token or generated) deletes the note. Unknown or lossy content returns 422 with field-level issues.",
    },
    components: {
      schemas: {
        ...PUBLISH_COMPONENT_SCHEMAS,
        PublishRequest: keylessPublishRequest,
        NoteSummary: summarySchema,
        PublishedNote: publicationSchema,
        LegacySettings: legacySettingsSchema,
      },
    },
    paths: {
      "/api/v1/notes": {
        post: {
          operationId: "createNote",
          summary: "创建手写笔记并返回分享链接（无需密钥）",
          description: "visibility 只能为 unlisted（默认）；public 返回 422。",
          parameters: [
            { name: "Idempotency-Key", in: "header", required: false, schema: { type: "string", maxLength: 100 }, description: "按客户端区分。相同键与请求体完成后重放原笔记（不返回 manageToken）；处理中返回 409 + Retry-After；删除后返回 410，不重新创建" },
            { name: "X-Manage-Token", in: "header", required: false, schema: { type: "string", pattern: "^[A-Za-z0-9._~-]{32,200}$" }, description: "可选：自己生成的删除凭据（高熵随机值）。提供后即使响应丢失也能删除；省略时由服务端生成并在 201 响应中返回" },
          ],
          requestBody: publishBody,
          responses: {
            "201": createdResponse,
            "200": { ...publishedResponse, description: "幂等重放，返回之前创建的笔记，不含 manageToken" },
            "400": errorResponse,
            "403": { ...errorResponse, description: "本站未开放免密钥发布" },
            "409": errorResponse,
            "410": { ...errorResponse, description: "对应笔记已删除；新建请使用新幂等键" },
            "413": errorResponse,
            "429": { ...errorResponse, description: "每分钟请求过多或 24 小时发布次数已达上限；遵循 Retry-After" },
            "422": errorResponse,
            "503": errorResponse,
          },
        },
      },
      "/api/v1/notes/validate": {
        post: {
          operationId: "validateNote", summary: "Validate prepared content without publishing or calling AI",
          description: "Checks the same contract as publication. Does not reserve an Idempotency-Key or create a note. Geometry and source fidelity are not checked.",
          requestBody: publishBody,
          responses: {
            "200": { description: "Valid structure; layout has not been measured", content: { "application/json": { schema: {
              type: "object", required: ["valid", "schemaVersion", "validation"],
              properties: { valid: { const: true }, schemaVersion: { const: 1 }, validation: validationSchema },
            } } } },
            "400": errorResponse, "403": errorResponse, "413": errorResponse, "422": errorResponse, "429": errorResponse,
          },
        },
      },
      "/api/v1/notes/{id}": {
        parameters: [noteIdParam],
        delete: {
          operationId: "deleteNote",
          summary: "用发布时返回的 manageToken 删除笔记",
          parameters: [{ name: "X-Manage-Token", in: "header", required: true, schema: { type: "string" } }],
          responses: { "204": { description: "已删除" }, "401": errorResponse, "404": { ...errorResponse, description: "笔记不存在或 manageToken 不正确" } },
        },
      },
      "/api/notes/{id}": {
        parameters: [noteIdParam],
        get: { operationId: "getPublicNote", summary: "公开读取笔记（无需密钥）", responses: { "200": publishedResponse, "404": errorResponse } },
      },
      "/api/gallery": {
        get: {
          operationId: "listGallery",
          summary: "图库中的公开笔记",
          parameters: [
            { name: "cursor", in: "query", schema: { type: "string" } },
            { name: "limit", in: "query", schema: { type: "integer", minimum: 1, maximum: 50, default: 20 } },
            { name: "template", in: "query", schema: { type: "string", enum: [...TEMPLATES] } },
            { name: "language", in: "query", schema: { type: "string", enum: ["zh", "en"] } },
          ],
          responses: { "200": { description: "笔记列表与下一页游标" } },
        },
      },
    },
  } as const;
}

export function llmsTxt(origin: string, recent: PublishedNoteSummary[] = []): string {
  const notes = recent.length
    ? `\n## 最近的公开笔记\n\n${recent.map((note) => `- [${note.title.replace(/[[\]]/g, "")}](${note.url})：${note.summary.replace(/\s+/g, " ")}`).join("\n")}\n`
    : "";
  return `# 墨语笔记 InkScribe

> 把文字整理为手写风格的单页笔记（康奈尔结构 + 手账排版），返回可以直接发给用户查看的链接。

墨语笔记是一个在线工具（${origin}）：用户粘贴文字或上传 TXT、Markdown、HTML、DOCX、PDF 文件，Workers AI 把内容整理为标题、线索关键词、分节要点与总结，再以手写字体排版在纸张上，可添加贴纸与插图，并导出 1x/2x/3x 的 PNG/JPG 图片。无需注册；编辑器草稿可保存在本机，服务端日志只记录元数据。Agent 发布只接收整理好的笔记，无需原文。

## 页面

- [编辑器](${origin}/)：粘贴文字、整理、排版与导出
- [图库](${origin}/gallery)：公开的笔记
- [使用说明](${origin}/guide)：网页操作步骤、AI agent 接入与常见问题
- [隐私政策](${origin}/privacy)：本地草稿、AI 处理、发布与删除的数据规则
- [使用条款](${origin}/terms)：内容权利、分享范围与 agent 使用责任
- 笔记查看页：\`${origin}/n/<id>\`，HTML 中包含笔记全文（标题、线索、分节与总结）

## 给 AI agent 的用法

- 无需注册或密钥，直接调用。按客户端 IP 限流，并有 24 小时发布次数上限（超出返回 429 + Retry-After）。
- 创建笔记：\`POST ${origin}/api/v1/notes\`，JSON 请求体必须包含 \`schemaVersion: 1\` 和 \`note\`（你已整理好的完整结构）。无需提交原文；\`text\` 以及生成专用的 \`language/detail/style\` 字段会被拒绝。
- \`note\` 必须包含 \`title/cues/sections/summary\`；可选 \`date/doodleTheme/doodleSpec/doodlePrompt\`。版式放在 \`appearance.layout\`，自定义插图放在 \`note.doodleSpec\`。
- 发布过程不调用 AI；请自行整理后提交。先读取 OpenAPI 获取完整约束，使用 \`POST ${origin}/api/v1/notes/validate\` 预检同一请求体。
- 预检只检查结构，返回 \`validation: {structure: "passed", layout: "not_checked"}\`；不保存笔记，也不验证内容事实。实际字体和溢出由浏览器渲染器检查。
- 非法字段、超长正文、无效重点短语或插图会返回 HTTP 422，\`error.issues\` 包含 \`path/code/message\`。修正后重新提交，不会悄悄截断内容。
- \`appearance.overflow\` 默认 \`expand\`：固定页面在可读字号内适配后仍放不下时扩成长图；选择 \`error\` 会保留固定尺寸，并在仍溢出时阻止图片导出。
- 返回的 \`url\` 即笔记查看页，直接发给用户。同时返回的 \`manageToken\` 是删除这篇笔记的唯一凭据，一并交给用户保存。
- \`visibility\` 只能是 \`unlisted\`（默认，持有链接可见，不进入图库，不被搜索引擎收录）；传 \`public\` 返回 422。
- 删除：\`DELETE ${origin}/api/v1/notes/<id>\`，请求头 \`X-Manage-Token: <manageToken>\`，成功返回 204。
- 每次发布带上 \`Idempotency-Key\`，网络重试保持原键与完全相同的 JSON 字段顺序。处理中返回 409 + Retry-After，完成后重放原链接（不再返回 \`manageToken\`）；删除后返回 410。修正内容时使用新键。
- 想在响应丢失时也能删除，可自己生成至少 32 位的随机值，发布时放在请求头 \`X-Manage-Token\` 中，它就是这篇笔记的 \`manageToken\`。

示例：

\`\`\`bash
curl -X POST ${origin}/api/v1/notes \\
  -H "Content-Type: application/json" \\
  -H "Idempotency-Key: weekly-review-2026-10-22" \\
  -d '{"schemaVersion":1,"note":{"title":"本周回顾","cues":[],"sections":[{"heading":"进展","content":"完成了导出功能。","highlights":["导出功能"]}],"summary":"下一步验证发布流程。"},"template":"meeting-minutes","appearance":{"paper":"kraft","ink":"brown"}}'
\`\`\`

模板：${TEMPLATES.join(", ")}；版式：${STYLES.join(", ")}；纸张：${ids(PAPERS).join(", ")}；墨水：${ids(INKS).join(", ")}。

## 文档

- [AI agent 接入指南](${origin}/guide#agents)
- [OpenAPI 规范](${origin}/api/v1/openapi.json)
- [图库](${origin}/gallery)
- [站点地图](${origin}/sitemap.xml)
${notes}`;
}
